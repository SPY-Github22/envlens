/**
 * Dotenv Template & Format Generator for EnvLens
 * 
 * Generates sanitized .env.example templates with smart dummy values
 * and formats existing .env files with key alignment and clean comments.
 */

import { MatrixRow } from './matrix';
import { EnvEntry } from './parser';
import { inferVariableType, InferredType } from './linter';

export interface GeneratorOptions {
  alignEquals?: boolean;
  alphabeticalSort?: boolean;
  includeComments?: boolean;
  quoteStrings?: boolean;
}

/**
 * Generate a smart placeholder based on key name and inferred type
 */
export function getSmartPlaceholder(key: string, sampleValue: string): string {
  const type: InferredType = inferVariableType(key, sampleValue);
  const lowerKey = key.toLowerCase();

  switch (type) {
    case 'port':
      return '3000';
    case 'boolean':
      return 'false';
    case 'number':
      return '100';
    case 'url':
      if (lowerKey.includes('db') || lowerKey.includes('database')) {
        return '"postgres://user:password@localhost:5432/dbname"';
      }
      if (lowerKey.includes('redis')) {
        return '"redis://localhost:6379"';
      }
      return '"http://localhost:3000"';
    case 'email':
      return '"admin@example.com"';
    case 'secret':
      if (lowerKey.includes('aws')) {
        return '"AKIAIOSFODNN7EXAMPLE"';
      }
      if (lowerKey.includes('stripe')) {
        return '"sk_test_your_key_here"';
      }
      if (lowerKey.includes('gh') || lowerKey.includes('github')) {
        return '"ghp_your_github_token_here"';
      }
      return `"your_${lowerKey}_here"`;
    default:
      if (sampleValue.toLowerCase() === 'development' || sampleValue.toLowerCase() === 'production') {
        return 'development';
      }
      return `"your_${lowerKey}_here"`;
  }
}

/**
 * Generates a clean, sanitized .env.example template from the multi-env matrix
 */
export function generateExampleTemplate(
  rows: MatrixRow[],
  options: GeneratorOptions = {}
): string {
  const {
    alignEquals = false,
    alphabeticalSort = true,
    includeComments = true,
  } = options;

  const sortedRows = alphabeticalSort
    ? [...rows].sort((a, b) => a.key.localeCompare(b.key))
    : [...rows];

  const lines: string[] = [];
  lines.push('# ========================================================');
  lines.push('# Generated by EnvLens (.env.example template)');
  lines.push('# Copy to .env and replace placeholder values with actual secrets');
  lines.push('# ========================================================\n');

  // Find max key length for alignment
  const maxKeyLen = alignEquals
    ? Math.max(...sortedRows.map(r => r.key.length), 0)
    : 0;

  for (const row of sortedRows) {
    if (includeComments && row.primaryComment) {
      lines.push(`# ${row.primaryComment}`);
    }

    // Pick first non-empty value among environments as sample
    let sampleVal = '';
    for (const valObj of Object.values(row.values)) {
      if (valObj.isPresent && valObj.value.trim()) {
        sampleVal = valObj.value;
        break;
      }
    }

    const placeholder = getSmartPlaceholder(row.key, sampleVal);
    const keyPart = alignEquals ? row.key.padEnd(maxKeyLen, ' ') : row.key;
    lines.push(`${keyPart}=${placeholder}`);
  }

  return lines.join('\n') + '\n';
}

/**
 * Formats existing .env entries with alignment and sorting
 */
export function formatDotEnv(
  entries: EnvEntry[],
  options: GeneratorOptions = {}
): string {
  const {
    alignEquals = false,
    alphabeticalSort = false,
    includeComments = true,
  } = options;

  const list = alphabeticalSort
    ? [...entries].sort((a, b) => a.key.localeCompare(b.key))
    : [...entries];

  const maxKeyLen = alignEquals
    ? Math.max(...list.map(e => e.key.length), 0)
    : 0;

  const lines: string[] = [];

  for (const entry of list) {
    if (includeComments && entry.precedingComments.length > 0) {
      for (const comment of entry.precedingComments) {
        lines.push(`# ${comment}`);
      }
    }

    let valStr = entry.value;
    if (entry.quoteType) {
      valStr = `${entry.quoteType}${valStr}${entry.quoteType}`;
    }

    const keyPart = alignEquals ? entry.key.padEnd(maxKeyLen, ' ') : entry.key;
    let line = `${keyPart}=${valStr}`;

    if (includeComments && entry.comment) {
      line += ` # ${entry.comment}`;
    }

    lines.push(line);
  }

  return lines.join('\n') + '\n';
}
